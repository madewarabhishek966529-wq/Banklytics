import PDFDocument from 'pdfkit';
import ExcelJS from 'exceljs';
import { formatINR, paiseToRupees } from '../utils/money.js';
import { analyzeFinancialHealth } from './financialIntelligence.js';

/**
 * Generates a professional PDF Financial Intelligence Report using PDFKit.
 */
export async function generatePDFReport({ transactions = [], statement = null, user = null }) {
  const intelligence = analyzeFinancialHealth({ transactions });
  const doc = new PDFDocument({ margin: 40, size: 'A4' });

  const buffers = [];
  doc.on('data', buffers.push.bind(buffers));

  // Primary Header
  doc.rect(40, 40, 515, 60).fill('#4f46e5');
  doc.fillColor('#ffffff').fontSize(20).text('BANKLYTICS FINANCIAL INTELLIGENCE REPORT', 55, 52, { bold: true });
  doc.fontSize(10).text(`Generated: ${new Date().toLocaleDateString()} | Confidential Personal Audit`, 55, 78);

  doc.moveDown(3);
  doc.fillColor('#1e293b');

  // Executive KPI Summary
  doc.fontSize(14).text('Executive Financial Summary', { underline: true });
  doc.moveDown(0.5);

  const { summary } = intelligence;
  doc.fontSize(10);
  doc.text(`Total Income Recorded: ${formatINR(summary.totalIncomePaise)}`);
  doc.text(`Total Debits & Outflows: ${formatINR(summary.totalExpensesPaise)}`);
  doc.text(`Real Consumption Spend (Excl. Transfers): ${formatINR(summary.actualConsumptionSpendPaise)}`);
  doc.text(`Peer-to-Peer & Internal Transfers: ${formatINR(summary.totalTransfersPaise)}`);
  doc.text(`Net Cash Flow: ${formatINR(summary.netCashFlowPaise)}`);
  doc.text(`Calculated Savings Rate: ${summary.savingsRate}%`);
  doc.text(`Financial Health Score: ${summary.healthScore} / 100`);

  doc.moveDown(1.5);

  // Top Spending Categories
  doc.fontSize(14).text('Spending Distribution by Category', { underline: true });
  doc.moveDown(0.5);
  doc.fontSize(9);

  for (const cat of intelligence.categoryBreakdown.slice(0, 8)) {
    doc.text(`• ${cat.category.padEnd(30, ' ')} ${formatINR(cat.totalPaise).padStart(15, ' ')} (${cat.percentage}%) - ${cat.count} txns`);
  }

  doc.moveDown(1.5);

  // Top Recipient Merchants
  if (intelligence.topMerchants.length > 0) {
    doc.fontSize(14).text('Top Recipient Merchants', { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(9);
    for (const m of intelligence.topMerchants.slice(0, 6)) {
      doc.text(`• ${m.merchant.padEnd(30, ' ')} ${formatINR(m.totalPaise).padStart(15, ' ')} (${m.count} payments)`);
    }
    doc.moveDown(1.5);
  }

  // Potential Savings Opportunities
  if (intelligence.savingsOpportunities.length > 0) {
    doc.fontSize(14).text('Analyst Savings Opportunities', { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(9);
    for (const s of intelligence.savingsOpportunities) {
      doc.text(`• [${s.category}] ${s.recommendation}`);
    }
    doc.moveDown(1.5);
  }

  // Anomalies / High-Value Debits
  if (intelligence.anomalies.length > 0) {
    doc.fontSize(14).text('Flagged Unusual / High-Value Transactions', { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(8);
    for (const a of intelligence.anomalies.slice(0, 5)) {
      const d = new Date(a.transaction.transactionDate).toLocaleDateString();
      doc.text(`• ${d} | ${a.transaction.description.slice(0, 40)} | ${formatINR(a.transaction.amountPaise)} (${a.reason})`);
    }
  }

  // Footer
  doc.fontSize(8).fillColor('#64748b').text('Generated by Banklytics Local Financial Engine. Strict Zero API Key Policy.', 40, 770, { align: 'center', width: 515 });

  doc.end();

  return new Promise((resolve) => {
    doc.on('end', () => {
      resolve(Buffer.concat(buffers));
    });
  });
}

/**
 * Generates a multi-sheet formatted Excel (.xlsx) workbook using ExcelJS.
 */
export async function generateExcelReport({ transactions = [], statement = null }) {
  const intelligence = analyzeFinancialHealth({ transactions });
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Banklytics';
  workbook.created = new Date();

  // Sheet 1: Executive Summary
  const summarySheet = workbook.addWorksheet('Executive Summary');
  summarySheet.columns = [
    { header: 'Metric', key: 'metric', width: 35 },
    { header: 'Value', key: 'value', width: 25 },
  ];

  summarySheet.addRows([
    { metric: 'Total Income', value: (intelligence.summary.totalIncomePaise / 100).toFixed(2) },
    { metric: 'Total Outflows (Debits)', value: (intelligence.summary.totalExpensesPaise / 100).toFixed(2) },
    { metric: 'Real Consumption Spend (Excl. Transfers)', value: (intelligence.summary.actualConsumptionSpendPaise / 100).toFixed(2) },
    { metric: 'Total Transfers (P2P / Self)', value: (intelligence.summary.totalTransfersPaise / 100).toFixed(2) },
    { metric: 'Net Cash Flow', value: (intelligence.summary.netCashFlowPaise / 100).toFixed(2) },
    { metric: 'Savings Rate (%)', value: `${intelligence.summary.savingsRate}%` },
    { metric: 'Financial Health Score (0-100)', value: intelligence.summary.healthScore },
    { metric: 'Total Transactions Analyzed', value: transactions.length },
  ]);

  // Sheet 2: Category Breakdown
  const catSheet = workbook.addWorksheet('Category Breakdown');
  catSheet.columns = [
    { header: 'Category', key: 'category', width: 30 },
    { header: 'Total Spend (INR)', key: 'total', width: 20 },
    { header: 'Percentage (%)', key: 'percentage', width: 15 },
    { header: 'Transaction Count', key: 'count', width: 18 },
  ];
  for (const c of intelligence.categoryBreakdown) {
    catSheet.addRow({
      category: c.category,
      total: (c.totalPaise / 100).toFixed(2),
      percentage: `${c.percentage}%`,
      count: c.count,
    });
  }

  // Sheet 3: Top Merchants
  const merchantSheet = workbook.addWorksheet('Top Merchants');
  merchantSheet.columns = [
    { header: 'Merchant', key: 'merchant', width: 30 },
    { header: 'Total Paid (INR)', key: 'total', width: 20 },
    { header: 'Transaction Count', key: 'count', width: 18 },
    { header: 'Category', key: 'category', width: 25 },
  ];
  for (const m of intelligence.topMerchants) {
    merchantSheet.addRow({
      merchant: m.merchant,
      total: (m.totalPaise / 100).toFixed(2),
      count: m.count,
      category: m.category,
    });
  }

  // Sheet 4: Transactions Master
  const txSheet = workbook.addWorksheet('Transactions');
  txSheet.columns = [
    { header: 'Date', key: 'date', width: 15 },
    { header: 'Description', key: 'desc', width: 45 },
    { header: 'Direction', key: 'dir', width: 12 },
    { header: 'Amount (INR)', key: 'amt', width: 15 },
    { header: 'Category', key: 'cat', width: 25 },
    { header: 'Classification', key: 'class', width: 18 },
    { header: 'Reference', key: 'ref', width: 20 },
  ];
  for (const t of transactions) {
    txSheet.addRow({
      date: new Date(t.transactionDate).toISOString().slice(0, 10),
      desc: t.description,
      dir: t.direction,
      amt: (t.amountPaise / 100).toFixed(2),
      cat: t.category,
      class: t.classification,
      ref: t.reference || '',
    });
  }

  return workbook.xlsx.writeBuffer();
}
